import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const source = await readFile(new URL('../workspace.js', import.meta.url), 'utf8');
const { validateItem, validateTool, parseEnvelope, descendants, filterItems, REVIEW_STEPS } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const project = { id: 'project', title: 'Outcome', type: 'Project', status: 'Open', description: '', context: '', parentId: null };
const task = { ...project, id: 'task', title: 'Action', type: 'Task', parentId: 'project' };
const child = { ...task, id: 'child', parentId: 'task' };
const items = [project, task, child];
for (const patch of [{ title: ' ' }, { title: 'x', type: 'Unknown' }, { title: 'x', status: 'Unknown' }, { title: 'x', context: null }, { title: 'x', id: 'forged' }, { parentId: 'missing' }, { parentId: 'project' }, { parentId: 'child' }]) assert.throws(() => validateItem(patch, items, project));
assert.equal(validateItem({ title: '  Capture  ' }, []).title, 'Capture');
assert.equal(validateItem({ parentId: null }, items, task).parentId, null);
assert.deepEqual(descendants(items, 'project').map(item => item.id), ['project', 'task', 'child']);
const moved = items.map(item => item.id === 'task' ? validateItem({ parentId: null }, items, task) : item);
assert.equal(moved.find(item => item.id === 'child').parentId, 'task');
assert.equal(filterItems(items).length, 3);
assert.equal(filterItems(items, { parentId: null }).length, 1);
assert.equal(filterItems(items, { parentId: 'project' })[0].id, 'task');
assert.throws(() => validateTool('create_item', { title: 'x', approved: true }));
assert.throws(() => validateTool('update_item', { id: 'task', patch: {} }));
assert.throws(() => validateTool('read_attribute', { id: 'task', attribute: '__proto__' }));
assert.throws(() => validateTool('list_items', { limit: 101 }));
assert.throws(() => validateTool('show_view', { view: 'all', itemId: 'task' }));
assert.throws(() => parseEnvelope('{"message":"done","tool":{"name":"arbitrary","arguments":{}}}'));
assert.throws(() => parseEnvelope('{"message":"","tool":null}'));
assert.throws(() => parseEnvelope('not JSON'));
assert.equal(parseEnvelope('{"message":"Ready","tool":null}').message, 'Ready');
assert.equal(REVIEW_STEPS.length, 11);
assert.equal(new Set(REVIEW_STEPS.map(step => step.id)).size, 11);
assert.equal(REVIEW_STEPS.filter(step => step.id.includes('calendar')).length, 2);
console.log('Shared production logic: integrity, hierarchy, filters, tool trust boundary, model envelope and all 11 review steps passed.');
